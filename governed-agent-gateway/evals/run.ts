import { existsSync, readFileSync } from "node:fs";
import { appendHistory, runSuite } from "./suite.js";
const version = process.env.EVAL_VERSION ?? process.argv[2] ?? "dev";
const r = runSuite();
for (const x of r.results) console.log(`${x.passed ? "PASS" : "FAIL"} ${x.id}${x.hard ? " [hard]" : ""} ${x.what}${x.message ? "  -> " + x.message : ""}`);
const hist = "evals/history.jsonl";
const prev = existsSync(hist) ? readFileSync(hist, "utf8").trim().split("\n").filter(Boolean).map((l) => JSON.parse(l)).at(-1) : null;
appendHistory(hist, { version, ts: new Date().toISOString(), score: r.score, passed: r.passed, total: r.total, hardFailures: r.hardFailures });
console.log(`\nscore ${r.passed}/${r.total} (${(r.score * 100).toFixed(0)}%), hard failures ${r.hardFailures}` + (prev ? `, previous ${prev.version}: ${(prev.score * 100).toFixed(0)}%` : ""));
if (r.hardFailures > 0 || r.score < 1) process.exit(1);
